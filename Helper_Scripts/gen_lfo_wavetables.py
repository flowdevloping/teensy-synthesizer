# This file generates the LFO shape tables used by the AudioLfoComplex class.
# It writes a C header file (AudioLfoWavetables.h) that can be included in the Teensy Synth firmware.
#
# Important distinction:
# - These tables define ONLY the SHAPE of the LFO oscillation (sine, triangle, saw, square).
# - They are NOT the audio-source wavetable (custom_wavetable.h) used by the wavetable synth.
# The LFO has no audio input; it generates its control signal purely from one of these tables.
#
# Requirements enforced by AudioLfoComplex::setWaveformTable():
# - The table length must be a power of two and at least 2.
# - Values are int16_t (-32767..32767) and represent exactly one full cycle.

# Import of Libraries
from pathlib import Path
import numpy as np

# Define output path
out_path = Path(__file__).resolve().parents[1] / "firmware" / "teensy_synth" / "AudioLfoWavetables.h"

# Number of samples per LFO table.
# 256 is a power of two -> shiftBits = 32 - ctz(256) = 24 (valid, <= 31).
LFO_WAVETABLE_SIZE = 256

# Normalized phase for one full cycle: t in [0, 1)
t = np.linspace(0.0, 1.0, LFO_WAVETABLE_SIZE, endpoint=False)

# 1. Define the LFO shapes (values in [-1.0, 1.0], one full cycle each).
# IMPORTANT: The order/names below must match LFO_SHAPE_IDS in Scripts/waveforms.py
# and the switch in the firmware serial parser:
#   0 = sine, 1 = triangle, 2 = saw, 3 = square
shapes = {
    "lfoSine": np.sin(2.0 * np.pi * t),
    "lfoTriangle": 2.0 * np.abs(2.0 * t - 1.0) - 1.0,
    "lfosaw": 2.0 * t - 1.0,
    "lfoSquare": np.where(t < 0.5, 1.0, -1.0),
}

# 2. Safe hardware conversion for the Teensy (16-Bit Integer).
# Clip to -32767..32767 to stay symmetric and avoid overflow to -32768.
def to_int16(samples: np.ndarray) -> np.ndarray:
    return np.clip(np.round(samples * 32767.0), -32767, 32767).astype(np.int16)

# 3. Write the tables to the .h file
with out_path.open("w", encoding="utf-8") as f:
    f.write("#pragma once\n#include <Arduino.h>\n\n")
    f.write("// Auto-generated by Helper_Scripts/gen_lfo_wavetables.py - do not edit by hand.\n")
    f.write("// LFO shape tables for AudioLfoComplex (one full cycle each, int16_t).\n")
    f.write("// Order matches LFO_SHAPE_IDS in Scripts/waveforms.py: sine, triangle, saw, square.\n\n")
    # Important: Using const to force the ARM compiler on the Teensy to keep the values
    # in Flash memory instead of SRAM (avoids wasting the limited SRAM).
    f.write(f"const uint16_t LFO_WAVETABLE_SIZE = {LFO_WAVETABLE_SIZE};\n\n")

    for name, shape in shapes.items():
        samples = to_int16(shape)
        f.write(f"const int16_t {name}[LFO_WAVETABLE_SIZE] = {{\n")
        for i, s in enumerate(samples):
            f.write(f"{int(s)},")
            if i % 16 == 15:
                f.write("\n")
        f.write("};\n\n")

print(f"Wrote to file: {out_path} ({len(shapes)} shapes x {LFO_WAVETABLE_SIZE} samples)")
